#!/usr/bin/env python3
"""Repository rules, checked on every pull request. Run from the repo root: python3 tests/check_repo.py"""
import os, re, subprocess, sys
fail = []
tracked = subprocess.run(["git", "ls-files"], capture_output=True, text=True).stdout.split("\n")
# 1. Nothing built is committed: the workflow builds from src/.
for f in tracked:
    if f in ("index.html", "sw.js") or f.startswith(("dist/", "site/", "_site/")) or f.endswith(".zip"):
        fail.append(f"built file committed: {f} (edit src/ and let the workflow build)")
# 2. The settings file the site loads exists at the root.
if not os.path.exists("firebase-config.js") or "DUALITY_FIREBASE" not in open("firebase-config.js").read():
    fail.append("firebase-config.js is missing at the root, or isn't the Duality settings file")
# 3. Licence: the app's name carries no Darrington Press marks; the required wording is present.
cfg = open("src/config.js", encoding="utf-8").read()
name = re.search(r'APP_NAME = "([^"]*)"', cfg).group(1)
if re.search(r"daggerheart|darrington|critical role|hope ?& ?fear", name, re.I):
    fail.append(f'APP_NAME "{name}" uses a Darrington Press mark (the licence forbids marks in a title)')
must = ["Daggerheart System Reference Document 2.0, © Critical Role, LLC", "Darrington Press Community Gaming (DPCGL) License",
        "not affiliated with, endorsed, or sponsored by Critical Role or Darrington Press", "Daggerheart™ Compatible"]
for doc in ("src/config.js", "ATTRIBUTION.md"):
    t = open(doc, encoding="utf-8").read()
    for m in must:
        if m not in t: fail.append(f'{doc}: missing the licence wording "{m}"')
# 4. The SRD data file is the generated one, with its attribution header.
d = open("src/srd-data.js", encoding="utf-8").read(400)
if "Daggerheart System Reference Document 2.0" not in d or "var SRD = " not in d:
    fail.append("src/srd-data.js doesn't look generated by tools/build_srd.py (header or 'var SRD' missing)")
for f in fail: print("FAIL:", f)
print("repository rules:", "FAILED" if fail else "ok")
sys.exit(1 if fail else 0)
