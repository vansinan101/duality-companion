#!/usr/bin/env python3
"""Pack the chosen game-icons.net icons (CC BY 3.0) into src/icons.js as path data.
Usage: python3 -I tools/build_icons.py <game-icons repo checkout> src/icons.js   (list in tools/icons.txt)"""
import json, os, re, sys
src, out = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.abspath(__file__))
icons, authors = {}, set()
for line in open(os.path.join(here, "icons.txt")):
    line = line.strip()
    if not line or line.startswith("#"): continue
    name, path = [x.strip() for x in line.split("=")]
    svg = open(os.path.join(src, path + ".svg")).read()
    ds = [d for d in re.findall(r'<path[^>]*\sd="([^"]+)"', svg) if d != "M0 0h512v512H0z"]
    icons[name] = " ".join(ds); authors.add(path.split("/")[0])
with open(out, "w") as f:
    f.write("/* Icons from game-icons.net by " + ", ".join(sorted(authors)) + ", licensed CC BY 3.0 (creativecommons.org/licenses/by/3.0).\n"
            "   Generated by tools/build_icons.py; don't edit by hand. */\n")
    f.write("var ICONS = " + json.dumps(icons, separators=(",", ":")) + ";\nvar ICON_AUTHORS = " + json.dumps(sorted(authors)) + ";\n")
print(len(icons), "icons,", os.path.getsize(out), "bytes; authors:", ", ".join(sorted(authors)))
